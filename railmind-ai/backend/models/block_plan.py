from sqlalchemy import (
    Column, Integer, String, Numeric, Date, Time, DateTime,
    Boolean, Text, ForeignKey, ARRAY, JSON
)
from sqlalchemy.orm import relationship
from sqlalchemy.sql import func

from models import Base


class BlockPlan(Base):
    """
    Represents an AI-generated optimized block schedule.

    A BlockPlan is the top-level container that holds multiple BlockWindows.
    It's generated by the MILP optimizer and goes through a lifecycle:
    DRAFT → APPROVED → ACTIVE → COMPLETED

    Each plan covers a section for a date range (typically weekly/monthly).
    """
    __tablename__ = "block_plans"

    id = Column(Integer, primary_key=True, index=True)
    plan_code = Column(
        String(30), unique=True, nullable=False, index=True,
        comment="Unique plan code e.g. 'BLK-MUM-W35-001'"
    )
    plan_type = Column(
        String(20), nullable=False,
        comment="Plan type: WEEKLY/MONTHLY"
    )
    section_id = Column(
        Integer, ForeignKey("railway_sections.id"), nullable=False, index=True
    )
    generated_at = Column(
        DateTime(timezone=True), server_default=func.now()
    )
    generated_by = Column(
        String(20), default="AI",
        comment="Who generated: AI/MANUAL"
    )
    plan_start_date = Column(Date, nullable=False)
    plan_end_date = Column(Date, nullable=False)

    # ─── AI Optimization Metrics ───
    total_blocks = Column(
        Integer, nullable=True,
        comment="Total number of block windows in this plan"
    )
    total_block_hrs = Column(
        Numeric(6, 1), nullable=True,
        comment="Total block hours allocated"
    )
    utilization_pct = Column(
        Numeric(5, 2), nullable=True,
        comment="Block utilization percentage (tasks filled vs available time)"
    )
    optimization_score = Column(
        Numeric(5, 2), nullable=True,
        comment="Optimizer objective function value (lower = better)"
    )
    tasks_scheduled = Column(
        Integer, nullable=True,
        comment="Number of maintenance tasks scheduled in this plan"
    )
    conflicts_resolved = Column(
        Integer, default=0,
        comment="Number of conflicts automatically resolved by AI"
    )

    # ─── Approval Workflow ───
    status = Column(
        String(20), default="DRAFT", index=True,
        comment="Plan status: DRAFT/APPROVED/ACTIVE/COMPLETED/REJECTED"
    )
    approved_by = Column(
        String(50), nullable=True,
        comment="Controller who approved the plan"
    )
    approved_at = Column(DateTime(timezone=True), nullable=True)
    rejection_reason = Column(Text, nullable=True)
    safety_report_data = Column(JSON, nullable=True, comment="Historical safety validation report")

    # ─── Relationships ───
    section = relationship("RailwaySection", back_populates="block_plans")
    block_windows = relationship(
        "BlockWindow", back_populates="plan", cascade="all, delete-orphan",
        order_by="BlockWindow.block_date, BlockWindow.start_time"
    )

    def __repr__(self):
        return (
            f"<BlockPlan(code='{self.plan_code}', type='{self.plan_type}', "
            f"status='{self.status}', blocks={self.total_blocks})>"
        )


class BlockWindow(Base):
    """
    Represents a single block window within a BlockPlan.

    A block window is a specific time slot on a specific day where
    railway traffic is stopped for maintenance work.

    Block types:
    - TRAFFIC: Line blocked for traffic (Engineering work)
    - POWER: OHE power switched off (TRD work)
    - DISCONNECTION: Signals disconnected (S&T work)
    - INTEGRATED: Multiple departments work simultaneously (optimal!)
    - MEGA: Extended block (4+ hours, usually Sunday)
    """
    __tablename__ = "block_windows"

    id = Column(Integer, primary_key=True, index=True)
    plan_id = Column(
        Integer, ForeignKey("block_plans.id"), nullable=False, index=True
    )
    block_code = Column(
        String(30), unique=True, nullable=False, index=True,
        comment="Unique block code e.g. 'BW-MUM-W35-003'"
    )
    block_date = Column(Date, nullable=False, index=True)
    start_time = Column(Time, nullable=False)
    end_time = Column(Time, nullable=False)
    duration_hrs = Column(
        Numeric(4, 1), nullable=False,
        comment="Block duration in hours"
    )
    section_id = Column(
        Integer, ForeignKey("railway_sections.id"), nullable=False, index=True
    )
    km_from = Column(
        Numeric(8, 2), nullable=False,
        comment="Start KM of the blocked section"
    )
    km_to = Column(
        Numeric(8, 2), nullable=False,
        comment="End KM of the blocked section"
    )
    block_type = Column(
        String(30), nullable=False,
        comment="Block type: TRAFFIC/POWER/DISCONNECTION/INTEGRATED/MEGA"
    )
    line_blocked = Column(
        String(10), nullable=False,
        comment="Which line is blocked: UP/DN/BOTH"
    )
    is_integrated = Column(
        Boolean, default=False,
        comment="Whether multiple departments share this block"
    )
    departments = Column(
        String(100), nullable=True,
        comment="Comma-separated departments: e.g. 'ENGG,SNT,TRD'"
    )
    status = Column(
        String(20), default="PLANNED", index=True,
        comment="Status: PLANNED/ACTIVE/COMPLETED/CANCELLED"
    )
    ai_explanation = Column(
        Text, nullable=True,
        comment="Natural language explanation of why AI chose this window"
    )

    # ─── Relationships ───
    plan = relationship("BlockPlan", back_populates="block_windows")
    section = relationship("RailwaySection", back_populates="block_windows")
    task_assignments = relationship(
        "BlockTaskAssignment", back_populates="block", cascade="all, delete-orphan",
        order_by="BlockTaskAssignment.sequence_order"
    )
    conflicts_as_primary = relationship(
        "ConflictLog", foreign_keys="ConflictLog.block_id_1",
        back_populates="block_primary", cascade="all, delete-orphan"
    )

    def __repr__(self):
        return (
            f"<BlockWindow(code='{self.block_code}', date={self.block_date}, "
            f"{self.start_time}-{self.end_time}, type='{self.block_type}')>"
        )

    @property
    def department_list(self) -> list[str]:
        """Parse departments string into a list."""
        if self.departments:
            return [d.strip() for d in self.departments.split(",")]
        return []


class BlockTaskAssignment(Base):
    """
    Links maintenance tasks to specific block windows.

    A block window can contain multiple tasks (especially integrated blocks),
    and tasks are executed in a specific sequence within the block.
    """
    __tablename__ = "block_task_assignments"

    id = Column(Integer, primary_key=True, index=True)
    block_id = Column(
        Integer, ForeignKey("block_windows.id"), nullable=False, index=True
    )
    task_id = Column(
        Integer, ForeignKey("maintenance_tasks.id"), nullable=False, index=True
    )
    sequence_order = Column(
        Integer, default=1,
        comment="Work sequence within the block (1 = first)"
    )
    start_offset_min = Column(
        Integer, default=0,
        comment="Minutes from block start when this task begins"
    )
    duration_min = Column(
        Integer, nullable=False,
        comment="Task duration in minutes within this block"
    )
    assigned_team = Column(
        String(50), nullable=True,
        comment="Assigned maintenance team e.g. 'SSE/P.Way/Kalyan'"
    )
    status = Column(
        String(20), default="ASSIGNED",
        comment="Status: ASSIGNED/IN_PROGRESS/COMPLETED/SKIPPED"
    )

    # ─── Relationships ───
    block = relationship("BlockWindow", back_populates="task_assignments")
    task = relationship("MaintenanceTask", back_populates="block_assignments")

    def __repr__(self):
        return (
            f"<BlockTaskAssignment(block={self.block_id}, task={self.task_id}, "
            f"seq={self.sequence_order})>"
        )


class ConflictLog(Base):
    """
    Records scheduling conflicts detected and resolved by the AI.

    Conflict types:
    - TRAIN_CLASH: Block window overlaps with a train's path
    - DEPT_OVERLAP: Two departments requesting the same section/time
    - RESOURCE: Required equipment not available
    - ADJACENT: Blocks too close together on the same corridor
    - PRIORITY: Higher priority task needs the same slot

    The AI proposes a resolution for each conflict, which the
    Explainability Dashboard displays to the controller.
    """
    __tablename__ = "conflict_log"

    id = Column(Integer, primary_key=True, index=True)
    detected_at = Column(
        DateTime(timezone=True), server_default=func.now()
    )
    conflict_type = Column(
        String(30), nullable=False, index=True,
        comment="Type: TRAIN_CLASH/DEPT_OVERLAP/RESOURCE/ADJACENT/PRIORITY"
    )
    description = Column(
        Text, nullable=False,
        comment="Human-readable description of the conflict"
    )
    block_id_1 = Column(
        Integer, ForeignKey("block_windows.id"), nullable=True, index=True
    )
    block_id_2 = Column(
        Integer, nullable=True,
        comment="Second conflicting block (if applicable)"
    )
    train_id = Column(
        Integer, ForeignKey("train_schedules.id"), nullable=True, index=True
    )
    resolution = Column(
        Text, nullable=True,
        comment="AI's proposed resolution in natural language"
    )
    resolution_type = Column(
        String(20), nullable=True,
        comment="Resolution action: RESCHEDULE/MERGE/SPLIT/CANCEL/REROUTE"
    )
    resolved = Column(Boolean, default=False, index=True)
    resolved_at = Column(DateTime(timezone=True), nullable=True)

    # ─── Relationships ───
    block_primary = relationship(
        "BlockWindow", foreign_keys=[block_id_1],
        back_populates="conflicts_as_primary"
    )
    train = relationship("TrainSchedule", back_populates="conflicts")

    def __repr__(self):
        return (
            f"<ConflictLog(type='{self.conflict_type}', "
            f"resolved={self.resolved})>"
        )
